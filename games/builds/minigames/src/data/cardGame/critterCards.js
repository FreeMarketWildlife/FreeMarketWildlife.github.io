export const getCritterCardById = (id) =>
  critterCards.find((card) => Number(card.id) === Number(id)) || null;

export const getCritterCardBySlug = (slug) =>
  critterCards.find((card) => card.slug === slug) || null;

export const getCritterCardsBySet = (setId) => critterCards.filter((card) => card.setId === setId);

export const getCritterCardsByType = (type) =>
  critterCards.filter((card) => card.types.includes(type));
