def font(display=False, narrow=False):
    factor=3 if display else 1
    em=2400 if display else 800
    fb=FontBuilder(em,isTTF=True)
    names=['.notdef']+[f'u{ord(c):04X}' for c in ROWS]
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap({ord(c):f'u{ord(c):04X}' for c in ROWS})
    glyphs={}; metrics={}
    for char,name in [('?', '.notdef')]+[(c,f'u{ord(c):04X}') for c in ROWS]:
        rows=ROWS[char]
        if display:
            rows=[''.join(c*(2 if narrow else 3) for c in row) for row in rows for _ in range(3)]
            # A one-grid-cell corner cut gives the display face its own pixel detail.
            old=rows[:]; grid=[list(r) for r in rows]
            for y,row in enumerate(old):
                for x,cell in enumerate(row):
                    if cell=='1' and y in (0,len(old)-1) and x in (0,len(row)-1):
                        grid[y][x]='0'
            rows=[''.join(r) for r in grid]
        pen=TTGlyphPen(None)
        h=len(rows)
        for y,row in enumerate(rows):
            x=0
            while x<len(row):
                if row[x]!='1': x+=1; continue
                end=x+1
                while end<len(row) and row[end]=='1': end+=1
                x0=x*100; x1=end*100; y0=(h-1-y)*100; y1=y0+100
                pen.moveTo((x0,y0));pen.lineTo((x0,y1));pen.lineTo((x1,y1));pen.lineTo((x1,y0));pen.closePath()
                x=end
        glyphs[name]=pen.glyph()
        metrics[name]=((len(rows[0])+(2 if narrow else factor))*100,0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=7*factor*100,descent=-factor*100)
    family='FMW Display Narrow' if narrow else ('FMW Display' if display else 'FMW Pixel')
    fb.setupNameTable({'familyName':family,'styleName':'Regular','uniqueFontIdentifier':family+'-1','fullName':family,'psName':family.replace(' ',''),'version':'Version 1.0'})
    fb.setupOS2(sTypoAscender=7*factor*100,sTypoDescender=-factor*100,sTypoLineGap=0,usWinAscent=7*factor*100,usWinDescent=factor*100)
    fb.setupPost();fb.setupMaxp()
    fb.save(ROOT/'assets/fonts'/('fmw-display-narrow.ttf' if narrow else ('fmw-display.ttf' if display else 'fmw-pixel.ttf')))
font();font(True);font(True,True)
