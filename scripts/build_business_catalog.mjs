import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const taxonomy=JSON.parse(fs.readFileSync(path.join(root,'docs/business-taxonomy.json'),'utf8'));
const labels=ns=>ns.flatMap(n=>[n.label,...labels(n.children)]);
const skillLabels=new Set(labels(taxonomy.skills)),interestLabels=new Set(labels(taxonomy.interests));
const dir=path.join(root,'content/business');
const files=fs.readdirSync(dir).filter(n=>n.endsWith('.json')).sort();
const catalog=files.flatMap(n=>JSON.parse(fs.readFileSync(path.join(dir,n),'utf8')));
const seen=new Set(),titles=new Set(),offers=new Set();
for(const b of catalog){
 for(const k of ['id','title','service','customer','family','needs','first'])if(typeof b[k]!=='string'||!b[k].trim())throw Error(`${b.id}: invalid ${k}`);
 if(!/^[a-z0-9-]+$/.test(b.id)||seen.has(b.id))throw Error('duplicate/invalid id '+b.id);seen.add(b.id);
 for(const [key,set] of [['skills',skillLabels],['interests',interestLabels]]){
  if(!Array.isArray(b[key])||!b[key].length||new Set(b[key]).size!==b[key].length)throw Error(`${b.id}: invalid ${key}`);
  for(const v of b[key])if(!set.has(v))throw Error(`${b.id}: unknown ${key} ${v}`);
 }
 for(const group of b.allInterests||[]){if(!Array.isArray(group)||!group.length)throw Error(`${b.id}: empty AND gate`);for(const v of group)if(!interestLabels.has(v))throw Error(`${b.id}: unknown AND gate ${v}`);}
 for(const [key,allowed] of Object.entries({startup:['Low','Moderate','High'],learning:['Short','Practiced','Deep'],growth:['Solo','Team','Scalable']}))if(!allowed.includes(b.ratings?.[key]))throw Error(`${b.id}: invalid rating ${key}`);
 const normalize=s=>s.toLowerCase().replace(/[^a-z0-9]/g,'');
 if(titles.has(normalize(b.title)))throw Error('duplicate title '+b.title);titles.add(normalize(b.title));
 const offer=normalize(b.service);if(offers.has(offer))throw Error('duplicate offer '+b.id);offers.add(offer);
 if(b.title.length>90||b.service.length>220||b.first.length>240)throw Error(`${b.id}: verbose card`);
}
if(catalog.length!==500)throw Error(`Expected 500 reviewed ideas; got ${catalog.length}`);
catalog.sort((a,b)=>a.id.localeCompare(b.id,'en'));
const output='// Generated by scripts/build_business_catalog.mjs. Edit content/business/*.json.\nexport const BUSINESSES = '+JSON.stringify(catalog,null,1)+';\n';
fs.writeFileSync(path.join(root,'assets/js/business-catalog.js'),output);
console.log(`Validated ${catalog.length} ideas from ${files.length} files; ${new Set(catalog.map(b=>b.family)).size} families.`);
