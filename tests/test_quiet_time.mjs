import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync('assets/js/quiet-time.js','utf8');
const {books,dateLabel,selectEntries}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(books.length,66);assert.equal(books.find(b=>b.name==='Psalms').chapters,150);
assert.equal(dateLabel('2026-10-18'),'Sunday, October 18th, 2026');
const entries=[{date:'2026-10-18',passage:'John 3:16–21'},{date:'2026-10-17',passage:'Genesis 1:1'},{date:'2026-10-16',passage:'1 John 3:16'}];
assert.equal(selectEntries(entries,{search:'John 3:18'}).length,1);
assert.equal(selectEntries(entries,{search:'John 3:30'}).length,0);
assert.equal(selectEntries(entries,{book:'John',chapter:'3'}).length,1);
assert.equal(selectEntries(entries,{book:'John',chapter:'4'}).length,0);
assert.equal(selectEntries(entries,{sort:'bible'})[0].passage,'Genesis 1:1');
assert.equal(selectEntries(entries,{sort:'oldest'})[0].date,'2026-10-16');
assert.equal(selectEntries(entries,{sort:'newest'})[0].date,'2026-10-18');
console.log('PASS: Bible metadata, ordinal date, verse-range search, book/chapter filters and three sort orders.');
const {validateEntries,readBackup,mergeEntries}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const oldEntry={date:'2026-10-18',passage:'John 3:16',quote:'Saved quote',prayer:'Saved prayer'};
const legacy=validateEntries([oldEntry]);
assert.equal(legacy[0].notes,'');assert.match(legacy[0].id,/^legacy-/);
const imported=readBackup(JSON.stringify({version:2,entries:[{id:'fixture-undated',date:null,passage:'Psalm 136:17–26',quote:'Quote',prayer:'Prayer',notes:'Reflection',sourceNote:'No date was supplied.'}]}));
assert.equal(dateLabel(imported[0].date),'Date not recorded');
const merged=mergeEntries(legacy,imported);assert.equal(merged.added,1);assert.equal(merged.entries.length,2);
assert.equal(mergeEntries(merged.entries,imported).skipped,1,'repeat imports do not duplicate entries');
assert.equal(mergeEntries(merged.entries,[{...legacy[0],prayer:'Replacement'}]).entries[0].prayer,'Saved prayer','ID conflicts never overwrite existing text');
for(const sort of ['oldest','newest'])assert.equal(selectEntries(merged.entries,{sort}).at(-1).date,null,'undated entries follow dated entries');
assert.equal(selectEntries(merged.entries,{book:'Psalms',chapter:'136'}).length,1);
assert.throws(()=>readBackup('{broken'));
assert.throws(()=>readBackup(JSON.stringify({version:3,entries:[]})));
assert.throws(()=>validateEntries([{...oldEntry,date:'2026-02-30'}]));
assert.throws(()=>validateEntries([{...oldEntry,quote:'x'.repeat(5001)}]));
assert.throws(()=>validateEntries([{...oldEntry,id:'same'},{...oldEntry,id:'same'}]));
assert.equal(validateEntries([{...oldEntry,quote:'x'.repeat(5000)}])[0].quote.length,5000);
assert.equal(readBackup(JSON.stringify({version:1,entries:[oldEntry]})).length,1);
console.log('PASS: legacy migration, undated records, import/export validation, repeat imports, non-overwriting merge and field limits.');
